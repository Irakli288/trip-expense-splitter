"""Списки допустимых значений для полей расхода.

Вынесены в отдельный файл, чтобы их могли брать и модели поездок,
не импортируя модель расхода (иначе импорт пошел бы по кругу).
"""

from django.db import models


class Category(models.TextChoices):
    """Категории расходов. Значения те же, что CATEGORIES из ПР3."""

    HOUSING = "жилье", "Жилье"
    TRANSPORT = "транспорт", "Транспорт"
    FOOD = "еда", "Еда"
    ENTERTAINMENT = "развлечения", "Развлечения"
    OTHER = "прочее", "Прочее"


class Status(models.TextChoices):
    """Учитывается ли расход в итогах и расчете.

    Отмененный расход (например, билеты сдали и деньги вернули)
    остается в истории, но не входит ни в суммы, ни в расчет долгов.
    """

    ACTIVE = "active", "Учитывается"
    CANCELLED = "cancelled", "Отменен"
