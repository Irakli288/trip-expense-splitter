"""Данные, которые нужны каждой странице сайта (шапка, меню)."""

from trips.models import Trip

SITE_NAME = "Сервис расходов поездки"


def site(request):
    """Название сайта и число поездок для меню.

    Число поездок передаем самим методом count, без вызова: шаблон
    вызовет его, только когда дойдет до меню. Страницы, где меню нет,
    лишнего запроса к базе не делают.
    """
    return {
        "site_name": SITE_NAME,
        "trips_count": Trip.objects.count,
    }
